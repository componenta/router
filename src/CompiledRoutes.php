<?php

declare(strict_types=1);

namespace Componenta\Http\Router;

use Componenta\Http\Router\Cache\RouteCacheGenerator;
use Componenta\Http\Router\Contract\CompilerInterface;
use Componenta\Http\Router\Contract\GeneratorInterface;
use Componenta\Http\Router\Contract\MatcherInterface;
use Componenta\Http\Router\Contract\RouteCollectorInterface;
use Componenta\Http\Router\Contract\SyntaxParserInterface;
use Componenta\Http\Router\Exception\MethodNotAllowedException;
use Componenta\Http\Router\Exception\RouteNotFoundException;
use Componenta\Http\Router\Exception\RouteNotRegisteredException;
use Componenta\Http\Router\Exception\RoutePatternException;
use Componenta\Http\Router\Internal\RouteRegex;
use Componenta\Http\Router\Internal\RoutePrefix;
use Componenta\Http\Router\Internal\RouteMatchIndex;
use Componenta\Http\Router\Internal\RouteDefinition;
use Componenta\Http\Router\Internal\PreparedMap;
use Componenta\Http\Router\Internal\RouteMethodGroups;
use Componenta\Http\Router\Internal\RouteParameters;
use Componenta\Http\Router\Internal\SourceRouteIndex;
use Componenta\Http\Router\Syntax\ColonSyntax;
use Componenta\Http\Router\Syntax\AngleBracketSyntax;
use Componenta\Http\Router\Syntax\CompositeSyntax;
use Componenta\Http\Router\Syntax\CurlySyntax;
use Componenta\Http\Router\Syntax\SquareBracketSyntax;
use Generator;

/**
 * Optimized route collection for production.
 *
 * Performance characteristics:
 * - Static routes: O(1) hash lookup, zero regex
 * - Dynamic routes: ordered individual expressions selected by literal path discriminators
 * - Cached RouteRecord instances for public access
 * - Pre-compiled regex patterns in cache
 * - Retains source syntax for URL generation
 */
final class CompiledRoutes implements RouteCollectorInterface, MatcherInterface, GeneratorInterface
{
    private readonly SyntaxParserInterface $sourceSyntax;
    public readonly CompilerInterface $compiler;
    /** Explicit URL generation syntax, or null to use the compiler syntax. */
    public readonly ?SyntaxParserInterface $syntax;

    /** @var array<string, RouteRecord> */
    private array $records = [];

    /** @param array<string, string> $defaultTokens */
    private function __construct(
        private readonly RouteMatchIndex $index,
        private readonly array $defaultTokens,
        private readonly array $routeData,
        ?SyntaxParserInterface $generationSyntax = null,
        ?SyntaxParserInterface $compilerSyntax = null,
        bool $explicitGenerationSyntax = true,
    ) {
        $this->compiler = new Compiler($compilerSyntax, $defaultTokens);
        $this->syntax = $explicitGenerationSyntax ? ($generationSyntax ?? new CompositeSyntax()) : null;
        $this->sourceSyntax = $this->syntax ?? $this->compiler->syntax;
    }

    private function matchResult(string $name, array $parameters): MatchResult
    {
        $route = $this->records[$name] ?? $this->getRoute($name);
        return new MatchResult($name, $route->handler, $route->middlewares, $parameters, $route);
    }

    /**
     * Create instance from cache file.
     *
     * @param string $cacheFile Path to cache file generated by RouteCacheGenerator
     */
    public static function fromCache(string $cacheFile): self
    {
        return self::fromArray(self::readCache($cacheFile) ?? throw new \RuntimeException('Cannot read route cache: ' . $cacheFile));
    }

    public static function fromArray(array $data): self
    {
        return self::tryFromArray($data) ?? throw new \InvalidArgumentException('Invalid or incompatible route cache; rebuild from the original source.');
    }

    private static function hydrate(array $data, RouteMatchIndex $index): self
    {
        return new self(
            $index,
            $data['defaultTokens'] ?? CompilerInterface::DEFAULT_PATTERNS,
            $data['routeData'] ?? [],
            self::syntaxFromCache(array_key_exists('generationSyntax', $data) ? $data['generationSyntax'] : CompositeSyntax::class),
            self::syntaxFromCache(array_key_exists('compilerSyntax', $data) ? $data['compilerSyntax'] : CompositeSyntax::class),
            $data['explicitGenerationSyntax'] ?? false,
        );
    }

    private static function syntaxFromCache(mixed $syntax): SyntaxParserInterface
    {
        return match ($syntax) {
            CompositeSyntax::class => new CompositeSyntax(),
            CurlySyntax::class => new CurlySyntax(),
            SquareBracketSyntax::class => new SquareBracketSyntax(),
            AngleBracketSyntax::class => new AngleBracketSyntax(),
            ColonSyntax::class => new ColonSyntax(),
            default => throw new \InvalidArgumentException('Unknown route cache syntax.'),
        };
    }

    /** Invalid or missing generated data leaves runtime resolution to the source. */
    public static function tryFromCache(string $file): ?self
    {
        return self::tryFromArray(self::readCache($file));
    }

    /** Read a trusted standalone deployment artifact, never user input. */
    private static function readCache(string $file): ?array
    {
        set_error_handler(static function (int $severity, string $message, string $file, int $line): never {
            throw new \ErrorException($message, 0, $severity, $file, $line);
        });
        try {
            clearstatcache(true, $file);
            if (is_link($file) || !is_file($file) || !is_readable($file)) {
                return null;
            }
            if (DIRECTORY_SEPARATOR === '/') {
                $permissions = fileperms($file);
                if ($permissions === false || ($permissions & 0o022) !== 0) {
                    return null;
                }
            }
            $level = ob_get_level();
            if (!ob_start()) { return null; }
            try {
                $data = (static fn (string $file): mixed => require $file)($file);
                return ob_get_level() === $level + 1 && ob_get_contents() === '' && is_array($data) ? $data : null;
            } finally {
                while (ob_get_level() > $level) {
                    if (!ob_end_clean()) { break; }
                }
            }
        } catch (\Throwable) {
            return null;
        } finally {
            restore_error_handler();
        }
    }

    /** Validate a prepared payload independently of its storage or application lifecycle. */
    public static function tryFromArray(mixed $data): ?self
    {
        set_error_handler(static function (int $severity, string $message, string $file, int $line): never {
            throw new \ErrorException($message, 0, $severity, $file, $line);
        });
        try {
            return self::fromCacheData($data);
        } catch (\Throwable) {
            return null;
        } finally {
            restore_error_handler();
        }
    }

    private static function fromCacheData(mixed $data): ?self
    {
        if (!is_array($data) || ($data['version'] ?? null) !== RouteCacheGenerator::CACHE_VERSION || !PreparedMap::valid($data)) { return null; }
        if (array_diff(array_keys($data), ['version','fingerprint','staticRoutes','dynamicIndex','methodAliases','defaultTokens','routeData','compilerSyntax','generationSyntax','explicitGenerationSyntax']) !== []) { return null; }
        if (array_key_exists('explicitGenerationSyntax', $data) && !is_bool($data['explicitGenerationSyntax'])) { return null; }
        foreach (['staticRoutes', 'dynamicIndex', 'methodAliases', 'defaultTokens', 'routeData'] as $key) {
            if (array_key_exists($key, $data) && !is_array($data[$key])) { return null; }
        }

        $validated = [];
        $contextSyntax = null;
        if (!self::isTokenShape($data['defaultTokens'] ?? []) || !self::areIndependentPatterns($data['defaultTokens'] ?? [], $validated)) { return null; }
        $expectedStatic = $expectedDynamic = $names = $regexes = $protectMark = [];
        $standardSyntax = ($data['compilerSyntax'] ?? CompositeSyntax::class) === CompositeSyntax::class;
        $defaultTokens = $data['defaultTokens'] ?? CompilerInterface::DEFAULT_PATTERNS;
        $records = $data['routeData'] ?? [];
        foreach ($records as $name => $route) {
            if (!is_array($route) || !is_string($route['path'] ?? null) || !array_key_exists('handler', $route)
                || array_diff(array_keys($route), ['path','handler','record','methods','middlewares','tokens','defaults','paramNames','optionalParams','group','regex']) !== []) { return null; }
            $raw = $route['record'] ?? [];
            if (!is_array($raw) || array_diff(array_keys($raw), ['tokens','defaults']) !== []) { return null; }
            foreach (['methods','middlewares','tokens','defaults','paramNames','optionalParams','record'] as $key) {
                if (array_key_exists($key, $route) && !is_array($route[$key])) { return null; }
            }
            foreach (['tokens','defaults'] as $key) {
                if (array_key_exists($key, $raw) && !is_array($raw[$key])) { return null; }
            }
            if (!self::isTokenShape($route['tokens'] ?? []) || !self::isTokenShape($route['optionalParams'] ?? [], true)) { return null; }
            $paramNames = $route['paramNames'] ?? [];
            if (!array_is_list($paramNames)) { return null; }
            foreach ($paramNames as $paramName) {
                if (!is_string($paramName) || $paramName === '') { return null; }
            }
            if (count(array_unique($paramNames)) !== count($paramNames)) { return null; }
            foreach ($route['defaults'] ?? [] as $paramName => $value) {
                if (!is_string($paramName) || $paramName === '' || (!is_scalar($value) && $value !== null)) { return null; }
            }
            // Validate shared definition fields without constructing every
            // handler wrapper, middleware group and public RouteRecord.
            RouteDefinition::validateName((string) $name);
            $path = $route['path'];
            $methods = $route['methods'] ?? [HttpMethod::GET];
            if (RouteDefinition::normalizePath($path) !== $path || RouteDefinition::normalizeMethods($methods) !== $methods
                || !array_is_list($route['middlewares'] ?? []) || (isset($route['group']) && !is_string($route['group']))) { return null; }
            RouteDefinition::tokens($raw['tokens'] ?? [], $validated);
            RouteDefinition::defaults($raw['defaults'] ?? []);
            if (!self::areIndependentPatterns($route['tokens'] ?? [], $validated) || !self::areIndependentPatterns($route['optionalParams'] ?? [], $validated)) {
                // Check contextual inline metadata without probing the route on an
                // empty subject again: that probe can exhaust runtime PCRE limits.
                $contextSyntax ??= self::syntaxFromCache($data['compilerSyntax'] ?? CompositeSyntax::class);
                $parsed = $contextSyntax->parse($path);
                $effectiveTokens = array_merge($defaultTokens, $parsed['tokens'], $raw['tokens'] ?? []);
                if (array_diff_assoc($effectiveTokens, $defaultTokens) !== ($route['tokens'] ?? [])
                    || $parsed['optionalParameters'] !== ($route['optionalParams'] ?? [])
                    || array_keys($parsed['parameters'] + $parsed['optionalParameters']) !== $paramNames) { return null; }
                if ($paramNames !== []) {
                    $expression = $contextSyntax->toRegex($path, $effectiveTokens);
                    $regex = $route['regex'] ?? null;
                    // The build may have added the omitted-root alternative. The
                    // trusted map records that choice; validate the actual PCRE below.
                    if ($regex !== RouteRegex::anchored($expression)
                        && $regex !== RouteRegex::anchored('(?:' . $expression . '|/)')) { return null; }
                }
            }
            $ordinal = count($names);
            $names[] = (string) $name;
            if ($paramNames !== []) {
                $regex = $route['regex'] ?? null;
                $tokens = [...$defaultTokens, ...($route['tokens'] ?? [])];
                $simple = $standardSyntax ? RouteRegex::simpleExpression($path, $tokens, $paramNames) : null;
                if (!is_string($regex) || ($simple !== null && $regex !== $simple)) { return null; }
                if ($simple === null) {
                    RouteRegex::validate($regex);
                    RouteRegex::assertUniqueParameterCaptures($regex, $paramNames);
                }
                $regexes[$ordinal] = $regex;
                if (in_array('MARK', $paramNames, true)) { $protectMark[$ordinal] = true; }
                $prefix = RoutePrefix::indexedKey($path, $standardSyntax, $tokens, $paramNames, $route['optionalParams'] ?? []);
            } elseif (array_key_exists('regex', $route)) { return null; }
            foreach ($methods as $method) {
                if ($paramNames !== []) {
                    $expectedDynamic[$method] ??= [];
                    RoutePrefix::add($expectedDynamic[$method], $prefix, $ordinal);
                } else {
                    if (isset($expectedStatic[$method][$path])) { return null; }
                    $expectedStatic[$method][$path] = (string) $name;
                }
            }
        }
        if (($data['staticRoutes'] ?? []) !== $expectedStatic) { return null; }
        $aliases = RouteMethodGroups::aliases($expectedDynamic);
        if (($data['methodAliases'] ?? []) !== $aliases || ($data['dynamicIndex'] ?? []) !== array_diff_key($expectedDynamic, $aliases)) { return null; }

        $dynamic = [];
        foreach ($expectedDynamic as $method => $buckets) {
            $dynamic[$method] = $data['dynamicIndex'][$aliases[$method] ?? $method];
        }
        return self::hydrate($data, new RouteMatchIndex($data['staticRoutes'] ?? [], $dynamic, $names, $regexes, $protectMark));
    }

    private static function isTokenShape(array $tokens, bool $nullable = false): bool
    {
        foreach ($tokens as $name => $pattern) {
            if (!is_string($name) || $name === '' || (!is_string($pattern) && !($nullable && $pattern === null))) { return false; }
        }
        return true;
    }

    private static function areIndependentPatterns(array $tokens, array &$validated): bool
    {
        foreach ($tokens as $pattern) {
            if ($pattern !== null && !isset($validated[$pattern])) {
                try {
                    RouteRegex::validateFragment($pattern);
                } catch (RoutePatternException) {
                    return false;
                }
                $validated[$pattern] = true;
            }
        }
        return true;
    }

    /**
     * Match URI against routes.
     *
     * @param RouteCollectorInterface $routes Route collection (should be $this for optimal performance)
     * @param string $uri URI to match
     * @param string $method HTTP method
     * @return MatchResult Match result with route and parameters
     * @throws MethodNotAllowedException If URI matches but method not allowed
     * @throws RouteNotFoundException If no route matches
     */
    public function match(RouteCollectorInterface $routes, string $uri, string $method): MatchResult
    {
        if ($routes !== $this) {
            return $routes instanceof MatcherInterface
                ? $routes->match($routes, $uri, $method)
                : $this->matchGeneric($routes, $uri, $method);
        }

        $name = $this->index->find($uri, $method, $matches);
        $route = $this->routeData[$name];
        return $this->matchResult($name, RouteParameters::extract($matches, $route['paramNames'] ?? [], $route['defaults'] ?? []));
    }

    /** Match an external collection using the same source matcher. */
    private function matchGeneric(RouteCollectorInterface $routes, string $uri, string $method): MatchResult
    {
        return (new SourceRouteIndex($routes, $this->compiler))->match($uri, $method);
    }

    /**
     * Generate URL for named route.
     *
     * @param RouteCollectorInterface $routes Route collection (should be $this for optimal performance)
     * @param string $name Route name
     * @param array<string, mixed> $parameters Route parameters
     * @return string Generated URL
     * @throws RouteNotRegisteredException If route not found
     */
    public function generate(RouteCollectorInterface $routes, string $name, array $parameters = []): string
    {
        if ($routes !== $this) {
            return $routes instanceof GeneratorInterface
                ? $routes->generate($routes, $name, $parameters)
                : $this->generateFromRoute($routes->getRoute($name), $parameters);
        }

        if (!isset($this->routeData[$name])) {
            throw new RouteNotRegisteredException($name);
        }

        $d = $this->routeData[$name];

        $path = $d['path'];

        return $this->sourceSyntax->buildPath(
            $path,
            $parameters + ($d['defaults'] ?? []),
            [
                ...$this->defaultTokens,
                ...($d['tokens'] ?? []),
            ],
            $d['optionalParams'] ?? [],
            $name
        );
    }

    /**
     * Generate URL from non-cached route.
     *
     * Compiles route on-the-fly and preserves its generation syntax.
     *
     * @param RouteRecord $route Route record
     * @param array<string, mixed> $parameters Route parameters
     * @return string Generated URL
     */
    private function generateFromRoute(RouteRecord $route, array $parameters): string
    {
        $compiled = $this->compiler->compile(
            $route->path,
            $route->tokens,
            $route->defaults
        );

        $syntax = $this->sourceSyntax;

        return $syntax->buildPath(
            $route->path,
            $parameters + $compiled->defaults,
            $compiled->tokens,
            $compiled->optionalParameters,
            $route->name
        );
    }

    /**
     * Check if route exists by name.
     */
    public function has(string $name): bool
    {
        return isset($this->routeData[$name]);
    }

    /**
     * Get route by name.
     *
     * @throws RouteNotRegisteredException If route not found
     */
    public function getRoute(string $name): RouteRecord
    {
        if (!isset($this->routeData[$name])) {
            throw new RouteNotRegisteredException($name);
        }

        if (!isset($this->records[$name])) {
            $data = $this->routeData[$name];
            $this->records[$name] = RouteRecord::fromArray([
                'name' => $name,
                'tokens' => $data['record']['tokens'] ?? [],
                'defaults' => $data['record']['defaults'] ?? [],
            ] + $data);
        }

        return $this->records[$name];
    }

    /**
     * Iterate over all routes.
     *
     * @return Generator<string, RouteRecord>
     */
    public function getIterator(): Generator
    {
        foreach ($this->routeData as $name => $data) {
            yield $name => $this->getRoute((string) $name);
        }
    }

    /**
     * Get total route count.
     */
    public function count(): int
    {
        return count($this->routeData);
    }

    /**
     * Convert to array of route records.
     *
     * @return array<string, RouteRecord>
     */
    public function toArray(): array
    {
        $routes = [];
        foreach ($this->routeData as $name => $_) {
            $routes[$name] = $this->getRoute((string) $name);
        }

        return $routes;
    }
}
